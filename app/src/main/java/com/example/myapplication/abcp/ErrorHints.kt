package com.example.myapplication.abcp

/**
 * Ошибки ABCP — понятным языком и с подсказкой, что делать. Незнакомые оставляем как есть (очищенными),
 * они уходят в AppMetrica — по отчётам добавляем сюда новые случаи.
 */
fun explainAbcpError(message: String?, httpCode: Int = 0): String {
    val m = message?.trim().orEmpty()
    val l = m.lowercase()
    return when {
        isBasketChanged(m) ->
            "Цена или наличие некоторых позиций изменились с момента, как вы положили их в корзину. " +
                "Проверьте позиции с ⚠ и подтвердите заказ ещё раз."
        "кредит" in l && ("лимит" in l || "превыш" in l) ->
            "Заказ не принят: превышен кредитный лимит. Оплатите долг в разделе «Заказы» (кнопка «Оплатить») " +
                "или позвоните менеджеру."
        "стоп" in l && "лист" in l ->
            "Оформление заказов для вашего аккаунта приостановлено. Позвоните менеджеру — он подскажет, что сделать."
        "минимальн" in l && ("сумм" in l || "заказ" in l) ->
            "$m\nДобавьте товаров в корзину или позвоните менеджеру."
        "кратн" in l || "упаков" in l ->
            "$m\nИзмените количество кнопками − / + в корзине — они учитывают упаковку."
        "нет в наличии" in l || "закончил" in l || "недоступ" in l && "позиц" in l ->
            "$m\nУдалите эту позицию из корзины и выберите другое предложение."
        "корзина пуста" in l || "пустая корзина" in l ->
            "Корзина пуста — возможно, заказ уже оформлен. Проверьте раздел «Заказы»."
        httpCode >= 500 || "internal server error" in l || "502 bad gateway" in l ->
            "Сервис магазина временно недоступен. Попробуйте через пару минут."
        m.isBlank() -> "Что-то пошло не так. Попробуйте ещё раз или напишите менеджеру в чат."
        else -> m
    }
}

/** Сетевые сбои (нет интернета, таймаут) — одним понятным текстом. */
fun networkErrorText(e: Throwable): String = when (e) {
    is java.net.UnknownHostException, is java.net.ConnectException ->
        "Нет связи с магазином. Проверьте интернет и попробуйте ещё раз."
    is java.io.InterruptedIOException ->
        "Магазин отвечает слишком долго. Попробуйте ещё раз."
    else -> "Связь прервалась. Проверьте интернет и попробуйте ещё раз."
}
